function parseAsciiArtSource(source){
  var comment = source.match(/\/\*([\s\S]*?)\*\//);
  if (!comment) throw new Error("ASCII art collection block was not found.");
  var entries = [];
  var currentName = null;
  var currentLines = [];

  function saveEntry(){
    if (currentName === null) return;
    while (currentLines.length && currentLines[0] === "") currentLines.shift();
    while (currentLines.length && currentLines[currentLines.length - 1] === "") currentLines.pop();
    var art = currentLines.join("\n");
    if (!art.trim()) throw new Error('ASCII art "' + currentName + '" is empty.');
    entries.push({ name: currentName, art: art });
  }

  comment[1].replace(/\r/g, "").split("\n").forEach(function(line){
    var marker = line.match(/^@@@\s+(.+?)\s*$/);
    if (marker){
      saveEntry();
      currentName = marker[1];
      currentLines = [];
    } else if (currentName !== null){
      currentLines.push(line);
    }
  });
  saveEntry();
  return entries;
}

